/**
 * glyph-modules.mjs — one real module per glyph in the built icon packages.
 *
 * ★★ WHY. ng-packagr flattens a package into ONE fesm file, and the
 *    `./glyph/*` subpath used to resolve to it. Tree-shaking still dropped the
 *    glyphs nobody imported, but bundlers split code per MODULE, not per
 *    statement: every glyph that ANY lazy page imported stayed in that one
 *    module, and the module sat in the initial chunk because `@styloviz/core`
 *    imports the icon package. An app with all 108 packages on lazy routes
 *    shipped 285 kB of glyph data in `main` (FL-L2's consumer smoke found it;
 *    the FL-B4 probe, one page, could not).
 *
 * After `ng build icons-free` / `ng build icons`, this writes, for every
 * generated glyph source (`src/generated/icons/<name>.icon.ts`):
 *
 *   fesm2022/glyph/<name>.mjs   the glyph's data — `<x>Nodes`, `<x>SolidNodes`,
 *                               `<x>Icon` — as plain objects, and its standalone
 *                               component re-exported from the package entry
 *   types/glyph/<name>.d.ts     the matching declarations
 *
 * and, for `@styloviz-pro/icons`, `fesm2022/free/<name>.mjs` + `types/free/<name>.d.ts`
 * re-exporting `@styloviz/icons/glyph/<name>`. The package.json `exports` map
 * (in the project source, copied by ng-packagr) points `./glyph/*` and
 * `./free/*` at these files. The data is copied verbatim from the generated
 * source — the same literals the package entry compiles — so the two cannot
 * draw different shapes.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const PACKAGES = {
  'icons-free': { name: '@styloviz/icons', dist: 'dist/@styloviz/icons', free: false },
  icons: { name: '@styloviz-pro/icons', dist: 'dist/@styloviz-pro/icons', free: true },
};

const HEADER = '// Generated by scripts/lib/glyph-modules.mjs after ng-packagr — one module per glyph.\n';

/** Parse one generated `<name>.icon.ts`: its data consts and its component class. */
export function parseGlyphSource(src, file) {
  const data = [...src.matchAll(/^export const (\w+): readonly IconNode\[\] = (\[\n[\s\S]*?\n\]);$/gm)].map((m) => ({ name: m[1], kind: 'nodes', value: m[2] }));
  const def = /^export const (\w+): SvIconDef = (\{[^\n]*\});$/m.exec(src);
  const cls = /^export class (\w+) extends \w+/m.exec(src)?.[1];
  if (!data.length || !cls) throw new Error(`glyph-modules: ${file} is not in the generated shape (nodes + component)`);
  return { data, def: def ? { name: def[1], value: def[2] } : null, cls };
}

/** The glyph names an icon project's generated barrel exports. */
function exportedGlyphs(root, project) {
  const index = readFileSync(join(root, 'projects', project, 'src/generated/index.ts'), 'utf8');
  return new Set([...index.matchAll(/from '\.\/icons\/([\w-]+)\.icon'/g)].map((m) => m[1]));
}

/** Emit the per-glyph modules for one built icon project. Returns the glyph count. */
export function emitGlyphModules(root, project) {
  const pkg = PACKAGES[project];
  if (!pkg) return 0;
  const dist = join(root, pkg.dist);
  if (!existsSync(join(dist, 'package.json'))) throw new Error(`glyph-modules: ${pkg.dist} is not built`);
  const srcDir = join(root, 'projects', project, 'src/generated/icons');
  // ★ Only glyphs the package's barrel exports get a module. A source the
  //   generator keeps but does not export (KEPT_ORPHANS in
  //   generate-icons-pro-stub.mjs — Pro `sparkles`) would otherwise ship as
  //   `glyph/<name>` re-exporting a class the package does not have: 2.0.0
  //   published `@styloviz-pro/icons/glyph/sparkles`, and importing it failed
  //   the buyer's build (registry run, 10 Nov 2026).
  const exported = exportedGlyphs(root, project);

  const fesmGlyph = join(dist, 'fesm2022/glyph');
  const typesGlyph = join(dist, 'types/glyph');
  for (const d of [fesmGlyph, typesGlyph]) {
    rmSync(d, { recursive: true, force: true });
    mkdirSync(d, { recursive: true });
  }

  const files = readdirSync(srcDir)
    .filter((f) => f.endsWith('.icon.ts') && exported.has(f.slice(0, -'.icon.ts'.length)))
    .sort();
  for (const f of files) {
    const glyph = f.slice(0, -'.icon.ts'.length);
    const { data, def, cls } = parseGlyphSource(readFileSync(join(srcDir, f), 'utf8'), f);
    const names = [...data.map((d) => d.name), ...(def ? [def.name] : [])];
    writeFileSync(
      join(fesmGlyph, `${glyph}.mjs`),
      HEADER +
        `export { ${cls} } from '${pkg.name}';\n\n` +
        data.map((d) => `const ${d.name} = ${d.value};\n`).join('') +
        (def ? `const ${def.name} = ${def.value};\n` : '') +
        '\n' +
        `export { ${names.join(', ')} };\n`,
    );
    writeFileSync(
      join(typesGlyph, `${glyph}.d.ts`),
      HEADER +
        `import type { IconNode, SvIconDef } from '@styloviz/icons';\n` +
        `export { ${cls} } from '${pkg.name}';\n` +
        data.map((d) => `export declare const ${d.name}: readonly IconNode[];\n`).join('') +
        (def ? `export declare const ${def.name}: SvIconDef;\n` : ''),
    );
  }

  if (pkg.free) {
    // `@styloviz-pro/icons/free/<n>`: the free glyph, by its own module.
    const freeSrc = join(root, 'projects/icons-free/src/generated/icons');
    const fesmFree = join(dist, 'fesm2022/free');
    const typesFree = join(dist, 'types/free');
    for (const d of [fesmFree, typesFree]) {
      rmSync(d, { recursive: true, force: true });
      mkdirSync(d, { recursive: true });
    }
    const freeExported = exportedGlyphs(root, 'icons-free');
    for (const f of readdirSync(freeSrc).filter((x) => x.endsWith('.icon.ts') && freeExported.has(x.slice(0, -'.icon.ts'.length)))) {
      const glyph = f.slice(0, -'.icon.ts'.length);
      const line = `export * from '@styloviz/icons/glyph/${glyph}';\n`;
      writeFileSync(join(fesmFree, `${glyph}.mjs`), HEADER + line);
      writeFileSync(join(typesFree, `${glyph}.d.ts`), HEADER + line);
    }
  }
  return files.length;
}
